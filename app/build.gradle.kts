// Apply the Google Services plugin only when google-services.json is present,
// so the project still compiles before Firebase has been configured.
// See docs/FIREBASE_SETUP.md.
if (file("google-services.json").exists()) {
    apply(plugin = libs.plugins.google.services.get().pluginId)
} else {
    logger.warn("google-services.json not found in app/ — Firebase will not work at runtime. See docs/FIREBASE_SETUP.md.")
}

// Read the Google Maps API key from local.properties (never committed).
val localProperties = Properties().apply {
    val f = rootProject.file("local.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}
